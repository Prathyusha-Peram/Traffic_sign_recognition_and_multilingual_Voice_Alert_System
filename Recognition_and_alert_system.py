def _gtts_cache(warning_key, lang):
    ck = (warning_key, lang)
    with _cache_lock:
        if ck in _audio_cache:
            return
    text = WARNINGS.get(warning_key, {}).get(lang, '')
    if not text:
        return
    # gTTS doesn't support 'pa'/'bn'/'ml' natively — fall back to English
    gtts_lang = lang if lang in ('en', 'te', 'hi', 'mr', 'ta', 'kn', 'bn', 'ml') else 'en'
    try:
        tts = gTTS(text=text, lang=gtts_lang, slow=False)
        fd, path = tempfile.mkstemp(suffix='.mp3')
        os.close(fd)
        tts.save(path)
        with _cache_lock:
            _audio_cache[ck] = path
    except Exception:
        pass


def preload_audio_cache(lang):
    for key in WARNINGS:
        if key == UNKNOWN_KEY:
            continue
        threading.Thread(target=_gtts_cache, args=(key, lang), daemon=True).start()


def _voice_worker():
    global _last_spoken_key, _last_spoken_time
    while True:
        try:
            warning_key, lang = _voice_queue.get(timeout=1)
        except queue.Empty:
            continue
        now = time.time()
        if warning_key == _last_spoken_key and (now - _last_spoken_time) < VOICE_COOLDOWN:
            continue
        _last_spoken_key  = warning_key
        _last_spoken_time = time.time()
        en_text = WARNINGS.get(warning_key, {}).get('en', 'Unknown sign detected.')
        with _cache_lock:
            cached = _audio_cache.get((warning_key, lang))
        if cached and os.path.exists(cached):
            try:
                pygame.mixer.music.load(cached)
                pygame.mixer.music.play()
                while pygame.mixer.music.get_busy():
                    time.sleep(0.05)
                continue
            except Exception:
                pass
        # Offline fallback
        try:
            if _tts_engine:
                _tts_engine.say(en_text)
                _tts_engine.runAndWait()
        except Exception as e:
            print(f"[pyttsx3] {e}")
        threading.Thread(target=_gtts_cache, args=(warning_key, lang), daemon=True).start()



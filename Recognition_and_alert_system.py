_frame_queue  = queue.Queue(maxsize=1)
_result_queue = queue.Queue(maxsize=1)


def _is_valid_box(x1, y1, x2, y2):
    w, h = x2 - x1, y2 - y1
    if w <= 0 or h <= 0 or w * h < MIN_BOX_AREA:
        return False
    ratio = w / h
    return MIN_ASPECT_RATIO <= ratio <= MAX_ASPECT_RATIO


def _inference_worker(model):
    while True:
        try:
            frame = _frame_queue.get(timeout=1)
        except queue.Empty:
            continue

        enhanced = preprocess_frame(frame)
        results  = model.predict(enhanced, conf=CONF_THRESHOLD, verbose=False)

        best_key        = None
        best_conf       = 0.0
        best_class_id   = -1
        best_box_coords = None

        for r in results:
            if not r.boxes:
                continue
            for box in r.boxes:
                x1, y1, x2, y2 = map(int, box.xyxy[0].tolist())
                if not _is_valid_box(x1, y1, x2, y2):
                    continue
                conf     = float(box.conf)
                class_id = int(box.cls)
                if conf > best_conf:
                    best_conf       = conf
                    best_class_id   = class_id
                    best_box_coords = (x1, y1, x2, y2)
                    
                    # Extract the true GTSRB integer from the model's class name (e.g. "traffic_sign_class_20" -> 20)
                    class_name_str = model.names[class_id]
                    try:
                        true_class_id = int(class_name_str.split('_')[-1])
                    except ValueError:
                        true_class_id = class_id  # Fallback
                    
                    # Map to known key, or UNKNOWN sentinel
                    best_key = GTSRB_CLASSES.get(true_class_id, UNKNOWN_KEY)

        annotated = None
        if best_key and best_box_coords is not None:
            annotated = frame.copy()
            x1, y1, x2, y2 = best_box_coords
            colour = (0, 220, 0) if best_key != UNKNOWN_KEY else (0, 100, 255)
            cv2.rectangle(annotated, (x1, y1), (x2, y2), colour, 3)
            label = f"{best_key}  {best_conf:.2f}"
            (lw, lh), _ = cv2.getTextSize(label, cv2.FONT_HERSHEY_SIMPLEX, 0.6, 2)
            cv2.rectangle(annotated, (x1, y1 - lh - 10), (x1 + lw + 8, y1), colour, -1)
            cv2.putText(annotated, label, (x1 + 4, y1 - 4),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.6, (0, 0, 0), 2)

        while not _result_queue.empty():
            try: _result_queue.get_nowait()
            except queue.Empty: break
        _result_queue.put_nowait((annotated, best_key, best_class_id))



# ═══════════════════════════════════════════════════════════════
#  UNKNOWN SIGN  — Bing image fetch
# ═══════════════════════════════════════════════════════════════
_fetched_img_cache = {}   # class_id → cv2 image (or None if failed)
_fetch_lock        = threading.Lock()

HEADERS = {
    'User-Agent': (
        'Mozilla/5.0 (Windows NT 10.0; Win64; x64) '
        'AppleWebKit/537.36 (KHTML, like Gecko) '
        'Chrome/120.0.0.0 Safari/537.36'
    )
}


def _fetch_sign_image(class_id: int, class_name: str):
    """
    Searches Bing Images for a reference photo of the traffic sign
    and stores the result in _fetched_img_cache[class_id].
    Runs in a background thread so it never blocks the camera loop.
    """
    query = class_name.replace('_', ' ') + ' traffic sign'
    search_url = (
        f"https://www.bing.com/images/search"
        f"?q={requests.utils.quote(query)}&form=HDRSC2&first=1"
    )
    try:
        resp = requests.get(search_url, headers=HEADERS, timeout=FETCH_TIMEOUT_SEC)
        resp.raise_for_status()

        # Parse the first image URL from Bing's JSON metadata
        import re
        # Bing embeds image URLs as "murl":"https://..." in the page source
        urls = re.findall(r'"murl":"(https?://[^"]+)"', resp.text)
        if not urls:
            raise ValueError("No image URLs found in Bing response")

        # Try URLs until one downloads successfully
        img = None
        for url in urls[:5]:
            try:
                r = requests.get(url, headers=HEADERS, timeout=FETCH_TIMEOUT_SEC, stream=True)
                r.raise_for_status()
                arr = np.frombuffer(r.content, np.uint8)
                candidate = cv2.imdecode(arr, cv2.IMREAD_COLOR)
                if candidate is not None and candidate.size > 0:
                    img = candidate
                    break
            except Exception:
                continue

        with _fetch_lock:
            _fetched_img_cache[class_id] = img
        if img is not None:
            print(f"[ImageFetch] Got reference image for class {class_id} ({class_name})")
        else:
            print(f"[ImageFetch] Could not decode any image for {class_name}")

    except Exception as e:
        print(f"[ImageFetch] Failed for {class_name}: {e}")
        with _fetch_lock:
            _fetched_img_cache[class_id] = None   # Mark as attempted


def get_or_fetch_sign_image(class_id: int, class_name: str):
    """
    Returns a cached image immediately, or triggers a background fetch
    and returns None until the image arrives.
    """
    with _fetch_lock:
        if class_id in _fetched_img_cache:
            return _fetched_img_cache[class_id]

    # Not fetched yet — kick off background thread
    _fetched_img_cache[class_id] = 'fetching'   # sentinel
    threading.Thread(
        target=_fetch_sign_image,
        args=(class_id, class_name),
        daemon=True,
        name=f"Fetch-{class_name}"
    ).start()
    return None


def make_reference_panel(ref_img, class_name: str, lang: str, frame_h: int):
    """
    Builds a side panel showing the fetched reference image
    with a header label and a localised message.
    """
    panel_w = 320
    panel   = np.zeros((frame_h, panel_w, 3), dtype=np.uint8)
    panel[:] = (20, 20, 50)

    # Header
    cv2.rectangle(panel, (0, 0), (panel_w, 50), (180, 60, 0), -1)
    cv2.putText(panel, "UNKNOWN SIGN", (8, 18),
                cv2.FONT_HERSHEY_DUPLEX, 0.55, (255, 255, 255), 1)
    cv2.putText(panel, "Reference from web:", (8, 38),
                cv2.FONT_HERSHEY_SIMPLEX, 0.45, (255, 220, 180), 1)

    # Reference image
    if ref_img is not None:
        target_h = min(260, frame_h - 140)
        target_w = panel_w - 20
        scale    = min(target_w / ref_img.shape[1], target_h / ref_img.shape[0])
        nw       = max(1, int(ref_img.shape[1] * scale))
        nh       = max(1, int(ref_img.shape[0] * scale))
        small    = cv2.resize(ref_img, (nw, nh))
        y_off    = 60
        x_off    = (panel_w - nw) // 2
        panel[y_off:y_off+nh, x_off:x_off+nw] = small
        y_text   = y_off + nh + 20
    else:
        y_text = 80
        cv2.putText(panel, "Fetching image...", (10, 130),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.55, (200, 200, 0), 1)

    # Class name label
    cv2.putText(panel, class_name.replace('_', ' ').title(),
                (8, min(y_text, frame_h - 60)),
                cv2.FONT_HERSHEY_SIMPLEX, 0.5, (100, 255, 100), 1)

    msg = WARNINGS[UNKNOWN_KEY].get(lang, WARNINGS[UNKNOWN_KEY]['en'])
    # Word-wrap message
    words   = msg.split()
    line    = ''
    y_msg   = min(y_text + 22, frame_h - 40)
    for w in words:
        test = (line + ' ' + w).strip()
        if cv2.getTextSize(test, cv2.FONT_HERSHEY_SIMPLEX, 0.4, 1)[0][0] > panel_w - 10:
            cv2.putText(panel, line, (8, y_msg),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.4, (200, 200, 200), 1)
            y_msg += 18
            line   = w
        else:
            line = test
    if line:
        cv2.putText(panel, line, (8, min(y_msg, frame_h - 5)),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.4, (200, 200, 200), 1)

    return panel


